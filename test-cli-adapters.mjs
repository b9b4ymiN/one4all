#!/usr/bin/env node

/**
 * Real CLI Adapter Test for BBIK Stock Analysis
 *
 * This script tests the one4all system with REAL CLI tools (Gemini, Codex, Claude)
 * No mock responses - actual LLM calls through installed CLI tools
 */

import { getKernelClient, resetKernelClient } from './packages/cli/dist/lib/kernel-client.js';

async function testCLIAdapters() {
  console.log('\n╔════════════════════════════════════════════════════════════════╗');
  console.log('║        BBIK Real CLI Adapter Test                            ║');
  console.log('║        Using REAL Gemini CLI, Codex CLI, Claude CLI          ║');
  console.log('╚════════════════════════════════════════════════════════════════╝\n');

  // Test each CLI adapter
  const cliTypes = ['gemini-cli', 'codex-cli', 'claude-cli'];

  console.log('🔍 STEP 1: Testing CLI Adapter Health');
  console.log('━'.repeat(70));

  const healthResults = {};

  for (const cliType of cliTypes) {
    try {
      resetKernelClient();
      const client = getKernelClient(cliType);
      const health = await client.getHealthStatus();

      const cliHealth = health.find(h => h.name.toLowerCase().includes('cli') && h.name.toLowerCase().includes(cliType.replace('-cli', '')));

      if (cliHealth?.status === 'online') {
        console.log(`   ✅ ${cliType}: ONLINE (${cliHealth.latency}ms latency)`);
        healthResults[cliType] = true;
      } else {
        console.log(`   ❌ ${cliType}: OFFLINE - ${cliHealth?.details || 'Unknown error'}`);
        healthResults[cliType] = false;
      }
    } catch (error) {
      console.log(`   ❌ ${cliType}: ERROR - ${error.message || error}`);
      healthResults[cliType] = false;
    }
  }

  // Find working CLI adapter
  const workingCLI = Object.keys(healthResults).find(key => healthResults[key]);

  if (!workingCLI) {
    console.log('\n❌ No CLI adapters are working. Cannot proceed with real test.');
    console.log('   Please ensure at least one CLI tool (gemini, codex, claude) is installed and authenticated.\n');
    return;
  }

  console.log(`\n✅ Using ${workingCLI} for real LLM calls\n`);

  // Create mission with real CLI adapter
  console.log('📋 STEP 2: Creating BBIK Mission');
  console.log('━'.repeat(70));

  resetKernelClient();
  const client = getKernelClient(workingCLI);

  const mission = await client.createMission({
    domain: 'investment-war-room',
    type: 'stock_analysis',
    ticker: 'BBIK',
    description: 'วิเคราะห์หุ้นกรุงเทพประกันภัย (BBIK) ด้วย DCF Valuation',
    assumptions: {
      growth_rate: '0.04',
      discount_rate: '0.105',
      margin_of_safety: '0.30'
    },
    cliAdapter: workingCLI
  });

  console.log(`   ✅ Mission ID: ${mission.mission_id}`);
  console.log(`   ✅ Ticker: ${mission.ticker} (กรุงเทพประกันภัย)`);
  console.log(`   ✅ CLI Adapter: ${workingCLI}`);
  console.log(`   ✅ State: ${mission.state}\n`);

  // Start mission
  console.log('🚀 STEP 3: Starting Mission');
  console.log('━'.repeat(70));

  const startResult = await client.startMission(mission.mission_id);

  if (startResult.success) {
    console.log(`   ✅ Mission started`);
    console.log(`   ✅ State: ${mission.state} → ${startResult.new_state}\n`);
  }

  // Real LLM Analysis
  console.log(`🤖 STEP 4: Real LLM Analysis via ${workingCLI}`);
  console.log('━'.repeat(70));

  const prompt = `คุณคือนักวิเคราะห์หลักทรัพย์มืออาชีพ ชำนาญด้านหุ้นประกันภัยไทย
กรุณาวิเคราะห์หุ้น BBIK (บมจ.กรุงเทพประกันภัย) โดย:

1. สรุปธุรกิจแบบสั้นๆ (2-3 ประโยค)
2. จุดแข็งของบริษัท (2-3 ข้อ)
3. ความเสี่ยงที่ต้องระวัง (2-3 ข้อ)
4. มุมมองน่าลงทุน / ไม่น่าลงทุนพร้อมเหตุผล

ตอบเป็นภาษาไทย กระชับ ไม่เกิน 200 คำ`;

  console.log(`   📝 Prompt: "${prompt.substring(0, 50)}..."`);
  console.log(`   ⏳ Waiting for ${workingCLI} response...\n`);

  const startTime = Date.now();
  const response = await client.askAgent({
    agent: 'damodaran-valuation',
    prompt: prompt,
    cliAdapter: workingCLI
  });
  const duration = Date.now() - startTime;

  console.log(`   ✅ Response received (${duration}ms)`);
  console.log(`   📄 Analysis Result:`);
  console.log('   ' + '─'.repeat(66));
  console.log(`   ${response.split('\n').join('\n   ')}`);
  console.log('   ' + '─'.repeat(66));

  // Save report
  console.log(`\n💾 STEP 5: Saving Report`);
  console.log('━'.repeat(70));

  const report = `
═══════════════════════════════════════════════════════════════
           BBIK (กรุงเทพประกันภัย) Real LLM Analysis Report
═══════════════════════════════════════════════════════════════

📊 Mission Details
   Mission ID: ${mission.mission_id}
   Ticker: BBIK (บมจ.กรุงเทพประกันภัย)
   CLI Adapter: ${workingCLI}
   Analysis Time: ${new Date().toLocaleString('th-TH')}
   Response Time: ${duration}ms

🤖 LLM Analysis:
${response}

═══════════════════════════════════════════════════════════════
  Generated by: one4all AI Company Simulation System
  Using: Real CLI Adapter (${workingCLI})
═══════════════════════════════════════════════════════════════
`;

  const reportPath = `/tmp/bbik-real-report-${Date.now()}.txt`;
  await import('fs').then(fs => {
    fs.writeFileSync(reportPath, report);
  });

  console.log(`   ✅ Report saved: ${reportPath}`);

  // Mission status
  console.log(`\n📊 STEP 6: Mission Status`);
  console.log('━'.repeat(70));

  const status = await client.getMissionStatus(mission.mission_id);
  console.log(`   ✅ Mission ID: ${status.mission_id}`);
  console.log(`   ✅ State: ${status.state}`);
  console.log(`   ✅ Duration: ${(status.current_state_duration / 1000).toFixed(2)}s`);

  // List all missions
  console.log(`\n📂 STEP 7: All Saved Missions`);
  console.log('━'.repeat(70));

  const allMissions = await client.listMissions({ limit: 5 });
  console.log(`   ✅ Total missions: ${allMissions.length}`);
  for (const m of allMissions) {
    console.log(`      • ${m.mission_id} - ${m.ticker || 'N/A'} (${m.state})`);
  }

  console.log('\n╔════════════════════════════════════════════════════════════════╗');
  console.log('║              Real CLI Test Complete! 🎉                          ║');
  console.log('║              No mocks - Real LLM responses                      ║');
  console.log('╚════════════════════════════════════════════════════════════════╝\n');
}

testCLIAdapters().catch(console.error);
